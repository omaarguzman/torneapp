with
pub_tables as (
  select c.oid, c.relname
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'r'
),
stmts(orden, sub, sql) as (
  -- 0. Encabezado
  select 0, '', 'set check_function_bodies = off;'

  -- 1. Tipos enum
  union all
  select 1, t.typname,
    format('create type public.%I as enum (%s);', t.typname,
      string_agg(quote_literal(e.enumlabel), ', ' order by e.enumsortorder))
  from pg_type t
  join pg_namespace n on n.oid = t.typnamespace
  join pg_enum e on e.enumtypid = t.oid
  where n.nspname = 'public'
  group by t.typname

  -- 2. Secuencias (por si alguna columna usa serial)
  union all
  select 2, c.relname, format('create sequence if not exists public.%I;', c.relname)
  from pg_class c join pg_namespace n on n.oid = c.relnamespace
  where n.nspname = 'public' and c.relkind = 'S'
    -- las de columnas identity se crean solas con la tabla
    and not exists (select 1 from pg_depend dp where dp.objid = c.oid and dp.deptype = 'i')

  -- 3. Funciones
  union all
  select 3, p.proname || '(' || pg_get_function_identity_arguments(p.oid) || ')',
    pg_get_functiondef(p.oid) || ';'
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'

  -- 4. Tablas con columnas
  union all
  select 4, t.relname,
    format('create table public.%I (%s);', t.relname,
      string_agg(
        format('%I %s', a.attname, format_type(a.atttypid, a.atttypmod))
        || case
             when a.attgenerated = 's' then ' generated always as (' || pg_get_expr(d.adbin, d.adrelid) || ') stored'
             when a.attidentity = 'a' then ' generated always as identity'
             when a.attidentity = 'd' then ' generated by default as identity'
             when d.adbin is not null then ' default ' || pg_get_expr(d.adbin, d.adrelid)
             else '' end
        || case when a.attnotnull then ' not null' else '' end,
        ', ' order by a.attnum))
  from pub_tables t
  join pg_attribute a on a.attrelid = t.oid and a.attnum > 0 and not a.attisdropped
  left join pg_attrdef d on d.adrelid = t.oid and d.adnum = a.attnum
  group by t.relname

  -- 5. Llaves primarias, únicas y checks (6. llaves foráneas, después)
  union all
  select case when co.contype = 'f' then 6 else 5 end,
    t.relname || '.' || co.conname,
    format('alter table public.%I add constraint %I %s;', t.relname, co.conname, pg_get_constraintdef(co.oid))
  from pg_constraint co join pub_tables t on t.oid = co.conrelid
  where co.contype in ('p', 'u', 'c', 'f', 'x')

  -- 7. Índices que no vienen de una restricción
  union all
  select 7, i.indexname, i.indexdef || ';'
  from pg_indexes i
  where i.schemaname = 'public'
    and not exists (
      select 1 from pg_constraint co
      join pg_class ic on ic.oid = co.conindid
      where ic.relname = i.indexname)

  -- 8. Vistas
  union all
  select 8, v.viewname, format('create view public.%I as %s', v.viewname, v.definition)
  from pg_views v where v.schemaname = 'public'

  -- 9. Triggers (tablas públicas y el de auth.users que crea el perfil)
  union all
  select 9, c.relname || '.' || tg.tgname, pg_get_triggerdef(tg.oid) || ';'
  from pg_trigger tg
  join pg_class c on c.oid = tg.tgrelid
  join pg_namespace n on n.oid = c.relnamespace
  where not tg.tgisinternal
    and (n.nspname = 'public'
      or (n.nspname = 'auth' and c.relname = 'users'
          and exists (select 1 from pg_proc p join pg_namespace pn on pn.oid = p.pronamespace
                      where p.oid = tg.tgfoid and pn.nspname = 'public')))

  -- 10. RLS
  union all
  select 10, t.relname, format('alter table public.%I enable row level security;', t.relname)
  from pub_tables t join pg_class c on c.oid = t.oid
  where c.relrowsecurity

  -- 11. Políticas (public y storage)
  union all
  select 11, p.schemaname || '.' || p.tablename || '.' || p.policyname,
    format('create policy %I on %I.%I as %s for %s to %s%s%s;',
      p.policyname, p.schemaname, p.tablename, lower(p.permissive), lower(p.cmd),
      array_to_string(array(select quote_ident(r) from unnest(p.roles) r), ', '),
      coalesce(' using (' || p.qual || ')', ''),
      coalesce(' with check (' || p.with_check || ')', ''))
  from pg_policies p
  where p.schemaname = 'public'
     or (p.schemaname = 'storage' and p.tablename = 'objects')

  -- 12. Permisos de tablas para anon / authenticated
  union all
  select 12, t.relname || '.0', format('revoke all on public.%I from anon, authenticated;', t.relname)
  from pub_tables t
  union all
  select 12, g.table_name || '.1',
    format('grant %s on public.%I to %I;', string_agg(g.privilege_type, ', '), g.table_name, g.grantee)
  from information_schema.role_table_grants g
  where g.table_schema = 'public' and g.grantee in ('anon', 'authenticated')
  group by g.table_name, g.grantee
  union all
  -- Permisos por columna (ej. profiles: solo full_name editable)
  select 12, cp.table_name || '.2',
    format('grant %s (%s) on public.%I to %I;', cp.privilege_type,
      string_agg(quote_ident(cp.column_name), ', '), cp.table_name, cp.grantee)
  from information_schema.column_privileges cp
  where cp.table_schema = 'public' and cp.grantee in ('anon', 'authenticated')
    and not exists (
      select 1 from information_schema.role_table_grants g
      where g.table_schema = 'public' and g.table_name = cp.table_name
        and g.grantee = cp.grantee and g.privilege_type = cp.privilege_type)
  group by cp.table_name, cp.grantee, cp.privilege_type

  -- 13. Quién puede ejecutar cada función
  union all
  select 13, p.proname || '.0',
    format('revoke all on function public.%I(%s) from public, anon, authenticated;',
      p.proname, pg_get_function_identity_arguments(p.oid))
  from pg_proc p join pg_namespace n on n.oid = p.pronamespace
  where n.nspname = 'public' and p.prokind = 'f'
  union all
  select 13, p.proname || '.1',
    format('grant execute on function public.%I(%s) to %s;',
      p.proname, pg_get_function_identity_arguments(p.oid),
      string_agg(distinct case when a.grantee = 0 then 'public' else quote_ident(r.rolname) end, ', '))
  from pg_proc p
  join pg_namespace n on n.oid = p.pronamespace
  cross join lateral aclexplode(coalesce(p.proacl, acldefault('f', p.proowner))) a
  left join pg_roles r on r.oid = a.grantee
  where n.nspname = 'public' and p.prokind = 'f'
    and (a.grantee = 0 or r.rolname in ('anon', 'authenticated', 'service_role'))
  group by p.oid, p.proname

  -- 14. Buckets de Storage
  union all
  select 14, b.id,
    format('insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types) values (%L, %L, %s, %s, %s) on conflict (id) do nothing;',
      b.id, b.name, b.public, coalesce(b.file_size_limit::text, 'null'),
      coalesce(quote_literal(b.allowed_mime_types::text) || '::text[]', 'null'))
  from storage.buckets b
)
select orden, sub, sql from stmts order by orden, sub;
